//! A frozen byte-level test vector pinning the on-disk wire format.
//!
//! # Why this exists
//!
//! Every other test in this crate feeds the parser bytes produced by
//! `tests/fixtures/synthetic.rs`. That makes them blind to a whole class of
//! bug: if the fixture writer and the parser agree on a *wrong* constant,
//! the round trip still succeeds. Three real interop bugs were shipped and
//! only found by trying an actual `.pqd` file from another implementation:
//!
//! 1. `checksum` was read at header offset 60 instead of 44.
//! 2. The element-type discriminants were `Scalar=1, Vector=2, Collection=3`
//!    instead of the reference's `Collection=1, Scalar=2, Vector=3`.
//! 3. Scalar embedding was inferred from `byte_size() < 8` rather than read
//!    from the wire's `isEmbedded` byte, so `Real8` values that real writers
//!    *do* embed were mis-decoded as links.
//!
//! The bytes below are written out literally, field by field, derived from
//! `GSF.PQDIF`'s `RecordHeader.cs` / `Element.cs` / `PhysicalWriter.cs` —
//! **not** generated by this crate's own code. If any of the three constants
//! above regresses, the corresponding assertion fails. Do not regenerate
//! this array from our writer; that would defeat its purpose.
//!
//! See also `tests/real_file_smoke.rs`, which checks the same properties
//! against a genuine file when one is supplied.

use std::io::Cursor;

use pqdif::{ChecksumMode, Element, PhysicalParser, PhysicalType};

/// One complete single-record PQDIF file: 64-byte header + 132-byte body.
///
/// Header (offsets absolute):
///
/// ```text
///   0..16   signature GUID 4a111440-e49f-11cf-9900-505144494600
///          -> on the wire: 4014114a 9fe4 cf11 9900505144494600
///          -> the tail spells "\x99\x00PQDIF\x00" in ASCII
///  16..32   type tag 89738606-f1c3-11cf-9d89-0080c72e70a3 (Container)
///  32..36   header_size      = 64
///  36..40   body_size        = 132
///  40..44   next_record_pos  = 0  (no successor)
///  44..48   checksum         = 0x2acc10e4  <-- NOT at 60..64
///  48..64   reserved, zeroed
/// ```
///
/// Body (offsets relative to the body, i.e. absolute minus 64):
///
/// ```text
///   0..4    top-level element count = 3
///
///   4..32   child 0 — tag 11111111-…, et=2 (Scalar), pt=41 (Real8),
///                     isEmbedded=1. Payload slot 20..28 holds the value
///                     bytes 2d431cebe2361a3f = 0.0001_f64. An 8-byte
///                     scalar that is nonetheless embedded: exactly the
///                     shape that a `size < 8` heuristic gets wrong.
///
///  32..60   child 1 — tag 22222222-…, et=3 (Vector), pt=10 (Char1),
///                     link=88, padded_size=12.
///
///  60..88   child 2 — tag 33333333-…, et=1 (Collection), link=100,
///                     padded_size=32.
///
///  88..100  vector payload: count=6, then "PQDIF\0", then 2 pad bytes.
/// 100..132  collection payload: count=1, then one 28-byte header —
///                     tag 44444444-…, et=2 (Scalar), pt=22 (Integer4),
///                     isEmbedded=1, value 4242.
/// ```
#[rustfmt::skip]
const WIRE: [u8; 196] = [
    // ---- record header ----
    // signature GUID
    0x40, 0x14, 0x11, 0x4a, 0x9f, 0xe4, 0xcf, 0x11,
    0x99, 0x00, 0x50, 0x51, 0x44, 0x49, 0x46, 0x00,
    // Container type tag
    0x06, 0x86, 0x73, 0x89, 0xc3, 0xf1, 0xcf, 0x11,
    0x9d, 0x89, 0x00, 0x80, 0xc7, 0x2e, 0x70, 0xa3,
    0x40, 0x00, 0x00, 0x00, // header_size      = 64
    0x84, 0x00, 0x00, 0x00, // body_size        = 132
    0x00, 0x00, 0x00, 0x00, // next_record_pos  = 0
    0xe4, 0x10, 0xcc, 0x2a, // checksum         = 0x2acc10e4  (offset 44!)
    0x00, 0x00, 0x00, 0x00, // reserved
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,

    // ---- record body ----
    0x03, 0x00, 0x00, 0x00, // top-level count = 3

    // child 0: embedded Real8 scalar = 0.0001
    0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11,
    0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11,
    0x02,                   // element type  = Scalar
    0x29,                   // physical type = Real8 (41)
    0x01,                   // isEmbedded    = true
    0x00,                   // reserved
    0x2d, 0x43, 0x1c, 0xeb, 0xe2, 0x36, 0x1a, 0x3f, // 0.0001_f64

    // child 1: Char1 vector, linked at body offset 88
    0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22,
    0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22,
    0x03,                   // element type  = Vector
    0x0a,                   // physical type = Char1 (10)
    0x00,                   // isEmbedded    = false
    0x00,                   // reserved
    0x58, 0x00, 0x00, 0x00, // link        = 88
    0x0c, 0x00, 0x00, 0x00, // padded_size = 12

    // child 2: Collection, linked at body offset 100
    0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33,
    0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33,
    0x01,                   // element type  = Collection
    0x00,                   // physical type = n/a
    0x00,                   // isEmbedded    = false
    0x00,                   // reserved
    0x64, 0x00, 0x00, 0x00, // link        = 100
    0x20, 0x00, 0x00, 0x00, // padded_size = 32

    // body offset 88 — vector payload: count then "PQDIF\0" then padding
    0x06, 0x00, 0x00, 0x00,
    0x50, 0x51, 0x44, 0x49, 0x46, 0x00,
    0x00, 0x00,

    // body offset 100 — collection payload: count then one child header
    0x01, 0x00, 0x00, 0x00,
    0x44, 0x44, 0x44, 0x44, 0x44, 0x44, 0x44, 0x44,
    0x44, 0x44, 0x44, 0x44, 0x44, 0x44, 0x44, 0x44,
    0x02,                   // element type  = Scalar
    0x16,                   // physical type = Integer4 (22)
    0x01,                   // isEmbedded    = true
    0x00,                   // reserved
    0x92, 0x10, 0x00, 0x00, // 4242_i32
    0x00, 0x00, 0x00, 0x00, // unused half of the payload slot
];

/// Parse [`WIRE`] with checksum verification left **on**, so the stored
/// Adler-32 at header offset 44 must match the body. Reading the checksum
/// from the wrong offset yields `0x00000000` here and fails.
fn parse_wire() -> pqdif::PhysicalRecord {
    let mut parser = PhysicalParser::new(Cursor::new(&WIRE[..])).expect("open wire vector");
    let record = parser
        .next_record()
        .expect("record decodes and checksum matches")
        .expect("one record present");
    assert!(
        parser.next_record().expect("terminator").is_none(),
        "next_record_pos is 0, so the chain must end after one record",
    );
    record
}

#[test]
fn header_fields_decode_at_reference_offsets() {
    let record = parse_wire();
    assert_eq!(record.offset, 0);
    assert_eq!(
        record.header.type_tag,
        uuid::uuid!("89738606-f1c3-11cf-9d89-0080c72e70a3"),
        "Container type tag",
    );
    assert_eq!(record.header.header_size, 64);
    assert_eq!(record.header.body_size, 132);
    assert_eq!(record.header.next_record_pos, 0);
    // The regression guard: checksum lives at bytes 44..48. Bytes 60..64 of
    // this vector are zero, so a parser reading the old offset sees 0 and
    // either mismatches or reports the wrong value here.
    assert_eq!(
        record.header.checksum, 0x2acc_10e4,
        "checksum must be read from header offset 44..48, not 60..64",
    );
}

#[test]
fn element_type_discriminants_match_reference() {
    let record = parse_wire();
    let children = &record.body.children;
    assert_eq!(children.len(), 3);

    // Wire bytes are 2, 3, 1 in that order. With the old (wrong) mapping
    // these would decode as Vector, Collection, Scalar respectively.
    assert!(
        matches!(children[0], Element::Scalar(_)),
        "element type 2 must decode as Scalar, got {:?}",
        children[0],
    );
    assert!(
        matches!(children[1], Element::Vector(_)),
        "element type 3 must decode as Vector, got {:?}",
        children[1],
    );
    assert!(
        matches!(children[2], Element::Collection(_)),
        "element type 1 must decode as Collection, got {:?}",
        children[2],
    );
}

#[test]
fn embedded_real8_scalar_uses_the_wire_flag() {
    let record = parse_wire();
    let Element::Scalar(scalar) = &record.body.children[0] else {
        panic!("child 0 must be a scalar");
    };
    assert_eq!(scalar.ty, PhysicalType::Real8);
    // Real8 is 8 bytes, so a `byte_size() < 8` heuristic treats this as a
    // link and reads 0x2d431ceb as a (negative) offset instead of decoding
    // the value. Real writers emit exactly this shape.
    assert_eq!(
        scalar.as_f64(),
        Some(0.0001),
        "isEmbedded=1 must win over any size-based heuristic",
    );
}

#[test]
fn linked_vector_payload_resolves_through_its_offset() {
    let record = parse_wire();
    let Element::Vector(vector) = &record.body.children[1] else {
        panic!("child 1 must be a vector");
    };
    assert_eq!(vector.ty, PhysicalType::Char1);
    assert_eq!(vector.len(), 6);
    assert_eq!(vector.values, b"PQDIF\0");
}

#[test]
fn nested_collection_resolves_and_embeds_its_child() {
    let record = parse_wire();
    let Element::Collection(collection) = &record.body.children[2] else {
        panic!("child 2 must be a collection");
    };
    assert_eq!(collection.children.len(), 1);
    let Element::Scalar(inner) = &collection.children[0] else {
        panic!("the nested child must be a scalar");
    };
    assert_eq!(inner.ty, PhysicalType::Integer4);
    assert_eq!(inner.as_i32(), Some(4242));
}

#[test]
fn tampering_with_the_body_trips_the_checksum() {
    // Confirms the checksum assertion above has teeth: the stored value at
    // offset 44 really is checked against these body bytes.
    let mut bytes = WIRE;
    bytes[64 + 4] ^= 0xff;
    let mut parser = PhysicalParser::new(Cursor::new(&bytes[..])).expect("open");
    assert!(
        matches!(
            parser.next_record(),
            Err(pqdif::PqdifError::ChecksumMismatch { .. })
        ),
        "a flipped body byte must fail verification",
    );
}

/// Zero the four checksum bytes at header offset 44..48, imitating a writer
/// that never computed one.
fn wire_with_absent_checksum() -> [u8; 196] {
    let mut bytes = WIRE;
    bytes[44..48].fill(0);
    bytes
}

/// Corrupt the body so the (still correct, non-zero) stored checksum no
/// longer matches it.
fn wire_with_corrupt_body() -> [u8; 196] {
    let mut bytes = WIRE;
    bytes[64 + 4] ^= 0xff;
    bytes
}

fn read_first(bytes: &[u8], mode: ChecksumMode) -> Result<(), pqdif::PqdifError> {
    let mut parser = PhysicalParser::new(Cursor::new(bytes)).expect("open");
    parser.checksum_mode(mode);
    parser.next_record().map(|_| ())
}

#[test]
fn always_mode_rejects_an_absent_checksum() {
    // The strict default cannot tell "not computed" from "corrupt", by
    // design: a zero field is a mismatch against this body.
    assert!(
        matches!(
            read_first(&wire_with_absent_checksum(), ChecksumMode::Always),
            Err(pqdif::PqdifError::ChecksumMismatch {
                expected: 0,
                actual: 0x2acc_10e4
            })
        ),
        "ChecksumMode::Always must reject a zero checksum field",
    );
}

#[test]
fn when_present_accepts_an_absent_checksum() {
    read_first(&wire_with_absent_checksum(), ChecksumMode::WhenPresent)
        .expect("a zero checksum field must be accepted as 'writer did not compute one'");
}

#[test]
fn when_present_still_catches_corruption_where_a_checksum_exists() {
    // The point of the mode: leniency is scoped to the *absent* case. A
    // record that does carry a checksum is held to it.
    assert!(
        matches!(
            read_first(&wire_with_corrupt_body(), ChecksumMode::WhenPresent),
            Err(pqdif::PqdifError::ChecksumMismatch { .. })
        ),
        "ChecksumMode::WhenPresent must verify records with a non-zero checksum",
    );
}

#[test]
fn when_present_accepts_a_valid_checksum() {
    read_first(&WIRE, ChecksumMode::WhenPresent).expect("a matching checksum must pass");
}

#[test]
fn never_mode_accepts_both_absent_and_corrupt() {
    read_first(&wire_with_absent_checksum(), ChecksumMode::Never).expect("absent, unverified");
    read_first(&wire_with_corrupt_body(), ChecksumMode::Never).expect("corrupt, unverified");
}

#[test]
fn default_mode_matches_explicit_always() {
    // `PhysicalParser::new` must start in the strict mode, so that a caller
    // who never mentions checksums gets verification.
    let absent = wire_with_absent_checksum();
    let mut parser = PhysicalParser::new(Cursor::new(&absent[..])).expect("open");
    assert!(
        matches!(
            parser.next_record(),
            Err(pqdif::PqdifError::ChecksumMismatch { .. })
        ),
        "an untouched parser must verify checksums",
    );
}

#[test]
fn verify_checksums_bool_maps_onto_the_enum() {
    // The `bool` shorthand predates ChecksumMode; it must stay equivalent to
    // the two modes it names, with no path to WhenPresent.
    let absent = wire_with_absent_checksum();

    let mut strict = PhysicalParser::new(Cursor::new(&absent[..])).expect("open");
    strict.verify_checksums(true);
    assert!(strict.next_record().is_err(), "true => Always");

    let mut lenient = PhysicalParser::new(Cursor::new(&absent[..])).expect("open");
    lenient.verify_checksums(false);
    assert!(lenient.next_record().is_ok(), "false => Never");

    let corrupt = wire_with_corrupt_body();
    let mut lenient = PhysicalParser::new(Cursor::new(&corrupt[..])).expect("open");
    lenient.verify_checksums(false);
    assert!(
        lenient.next_record().is_ok(),
        "false must be Never, not WhenPresent",
    );
}
